CREATE TABLE mp_sceneplugincloud_scene_config (
    `pk` int(11) NOT NULL AUTO_INCREMENT COMMENT '主键',
    `id` varchar(64)  NOT NULL COMMENT 'id',
    `scene` varchar(64) NOT NULL COMMENT '场景模板id',
    `create_time` datetime(6) NOT NULL COMMENT '创建时间',
    `update_time` datetime(6) NOT NULL COMMENT '更新时间',
    PRIMARY KEY (`pk`),
    UNIQUE (`id`),
    UNIQUE (`scene`)
);

CREATE TABLE mp_sceneplugincloud_scene_config_element (
    `pk` int(11) NOT NULL AUTO_INCREMENT COMMENT '主键',
    `id` varchar(64)  NOT NULL COMMENT 'id',
    `scene` varchar(64) NOT NULL COMMENT '场景模板id',
    `scene_element` varchar(64) NOT NULL COMMENT '节点id',
    `external` tinyint(1) NOT NULL COMMENT '是否外部引用资源',
    `virtual_type` int(10) NOT NULL COMMENT '云平台虚拟化类型',
    `resource_id` varchar(64) NOT NULL COMMENT '云平台虚拟化资源id',
    `electric_port_number` int(10) NOT NULL COMMENT '电口数量',
    `electric_port_type` varchar(8) NOT NULL COMMENT '电口类型',
    `optical_port_number` int(10) NOT NULL COMMENT '光口数量',
    `optical_port_type` varchar(8) NOT NULL COMMENT '光口类型',
    `cidr` varchar(32) NOT NULL COMMENT '虚拟交换机cidr地址段',
    `gateway` varchar(32) NOT NULL COMMENT '虚拟交换机网关',
    `dns_nameservers` varchar(255) NOT NULL COMMENT '虚拟交换机dns',
    `dhcp` tinyint(1) NOT NULL COMMENT '虚拟交换机是否开启dhcp',
    `allocation_pools` varchar(1024) NOT NULL COMMENT '虚拟交换机地址池',
    `vlan` tinyint(1) NOT NULL COMMENT '虚拟交换机vlan模式',
    `vlan_id` int(10) NOT NULL COMMENT '虚拟交换机vlanId',
    `static_routes` varchar(1024) NOT NULL COMMENT '虚拟路由静态路由',
    `firewall_ingress_rules` varchar(1024) NOT NULL COMMENT '虚拟防火墙入口规则',
    `firewall_egress_rules` varchar(1024) NOT NULL COMMENT '虚拟防火墙出口规则',
    `image` varchar(64) NOT NULL COMMENT '虚拟机/容器镜像名称',
    `initial_tools` varchar(2048) NOT NULL COMMENT '终端初始包含工具',
    `auxiliary_network_on` tinyint(1) NOT NULL COMMENT '是否开启辅助网络',
    `auxiliary_network_id` varchar(64) NOT NULL COMMENT '辅助网络id',
    `auxiliary_network_cidr` varchar(32) NOT NULL COMMENT '辅助网络cidr地址段',
    `auxiliary_network_gateway` varchar(32) NOT NULL COMMENT '辅助网络网关',
    `auxiliary_network_dns_nameservers` varchar(255) NOT NULL COMMENT '辅助网络dns',
    `auxiliary_network_dhcp` tinyint(1) NOT NULL COMMENT '辅助网络是否开启dhcp',
    `auxiliary_network_allocation_pools` varchar(1024) NOT NULL COMMENT '辅助网络地址池',
    `auxiliary_network_vlan` tinyint(1) NOT NULL COMMENT '辅助网络vlan模式',
    `auxiliary_network_vlan_id` int(10) NOT NULL COMMENT '辅助网络vlanId',
    `create_time` datetime(6) NOT NULL COMMENT '创建时间',
    `update_time` datetime(6) NOT NULL COMMENT '更新时间',
    PRIMARY KEY (`pk`),
    UNIQUE (`id`),
    UNIQUE (`scene`, `scene_element`)
);

